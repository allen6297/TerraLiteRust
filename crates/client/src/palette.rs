fn hashed(id: &str, metadata: u8) -> [f32; 3] {
    let mut n = u32::from(metadata) * 17 + 11;
    for byte in id.bytes() {
        n = n.wrapping_mul(37).wrapping_add(u32::from(byte));
    }
    let channel = |mul: u32| ((n.wrapping_mul(mul) % 180) + 40) as f32 / 255.0;
    [channel(13), channel(29), channel(47)]
}
